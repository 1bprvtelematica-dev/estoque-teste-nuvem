        CREATE TABLE IF NOT EXISTS seq_recibo(id INTEGER PRIMARY KEY CHECK(id=1),valor INTEGER NOT NULL DEFAULT 0);
        CREATE TABLE IF NOT EXISTS logs_sistema(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,usuario TEXT,acao TEXT,data TEXT);
        CREATE TABLE IF NOT EXISTS solicitacoes_usuarios(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,usuario TEXT UNIQUE NOT NULL,senha TEXT NOT NULL,data TEXT NOT NULL);
